function seededBlock(
  type: BlockType,
  id: string,
  patch: SeedPatch,
): DashboardBlock {
  const block = createBlock(type, {}, "human");
  const {
    style,
    chart,
    table: tableSettings,
    kpi: kpiSettings,
    layout,
    ...flat
  } = patch;
  Object.assign(block, flat);
  block.id = id;
  block.createdAt = STAMP;
  block.updatedAt = STAMP;
  block.style = {
    ...block.style,
    cornerRadius: 11,
    shadow: "none",
    ...style,
  };
  block.chart = { ...block.chart, ...chart };
  block.table = { ...block.table, ...tableSettings };
  block.kpi = { ...block.kpi, ...kpiSettings };
  block.layout = { ...block.layout, ...layout };
  return block;
}

function asset(
  id: string,
  name: string,
  description: string,
  months: DatasetMonth[],
  headerMap: Record<string, string>,
): DataAsset {
  const latestReady = [...months]
    .filter((item) => item.status !== "pending")
    .sort((a, b) => b.period.localeCompare(a.period))[0];
  return {
    id,
    name,
    description,
    createdAt: "2026-08-31T14:12:00.000Z",
    updatedAt: STAMP,
    months,
    recipe: {
      id: `${id}-recipe`,
      name: `${name} monthly normalization`,
      headerMap,
      notes: latestReady?.cleaningSummary ?? [],
      updatedAt: STAMP,
    },
  };
}

